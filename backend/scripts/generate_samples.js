async function run() {
  fs.mkdirSync(TARGET_DIR, { recursive: true });
  console.log(`=== SENTETIK ÖRNEK FİŞ ÜRETİCİ ===`);
  console.log(`Hedef Klasör: ${TARGET_DIR}\n`);

  for (let i = 0; i < templates.length; i++) {
    const t = templates[i];
    const fileName = `${String(i + 1).padStart(2, '0')}_${t.name}.png`;
    const destPath = path.join(TARGET_DIR, fileName);

    try {
      const svg = receiptSvg(t.lines);
      const buffer = await sharp(Buffer.from(svg)).png().toBuffer();
      fs.writeFileSync(destPath, buffer);
      console.log(`  [${i + 1}/${templates.length}] Üretildi: ${fileName}`);
    } catch (e) {
      console.error(`  ❌ Hata (${t.name}):`, e.message);
    }
  }

  console.log(`\n🎉 Toplam ${templates.length} adet örnek fiş görseli başarıyla üretildi!`);
}

run();
