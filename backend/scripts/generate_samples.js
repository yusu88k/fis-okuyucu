// SVG oluşturucu
function receiptSvg(lines) {
  const lineHeight = 34;
  const height = lines.length * lineHeight + 85;
  const textLines = lines
    .map((line, i) => `<text x="35" y="${65 + i * lineHeight}" font-family="DejaVu Sans Mono, monospace" font-size="20" font-weight="bold" fill="#111">${line.replace(/&/g, '&amp;').replace(/</g, '&lt;')}</text>`)
    .join('\n');
  return `<svg xmlns="http://www.w3.org/2000/svg" width="540" height="${height}"><rect width="100%" height="100%" fill="#fafaf4" stroke="#ddd" stroke-width="2"/>${textLines}</svg>`;
}

